int helpLineCount = sizeof(helpDE) / sizeof(helpDE[0]);

void help_init(bool german) {
	if (german) {
		helpText = helpDE;
		helpLineCount = sizeof(helpDE) / sizeof(helpDE[0]);
	} else {
		helpText = helpEN;
		helpLineCount = sizeof(helpEN) / sizeof(helpEN[0]);
	}
}
